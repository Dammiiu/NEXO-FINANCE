// Normalises whatever the client sends: trims, collapses inner whitespace, and
// rejects values that are not on the list. Registration previously accepted any
// string, so "usa" and "United States" both landed in the same column.
export const normalizeCountry = (value: unknown): string | null => {
  if (typeof value !== 'string') return null;
  const cleaned = value.trim().replace(/\s+/g, ' ');
  if (!cleaned) return null;
  const match = COUNTRIES.find((c) => c.toLowerCase() === cleaned.toLowerCase());
  return match || null;
};